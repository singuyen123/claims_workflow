import { useEffect, useRef, useState } from 'react';

type Mermaid = typeof import('mermaid').default;

let loading: Promise<Mermaid> | undefined;
let counter = 0;

/** Mermaid is large, so it is loaded on first use. */
function loadMermaid(): Promise<Mermaid> {
  loading ??= import('mermaid').then(({ default: mermaid }) => {
    mermaid.initialize({ startOnLoad: false, securityLevel: 'strict', theme: 'neutral' });
    return mermaid;
  });
  return loading;
}

/** Renders the state diagram the API generates from the claim's pinned workflow definition. */
export function StateDiagram({ text }: { text: string }) {
  const container = useRef<HTMLDivElement>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    let active = true;
    loadMermaid()
      .then((mermaid) => mermaid.render(`state-diagram-${++counter}`, text))
      .then(({ svg }) => {
        if (active && container.current) {
          // Rendered by mermaid with securityLevel "strict" from text generated by our API.
          container.current.innerHTML = svg;
          setError(null);
        }
      })
      .catch((e: unknown) => {
        if (active) setError(e instanceof Error ? e.message : String(e));
      });
    return () => {
      active = false;
    };
  }, [text]);

  return (
    <div>
      <div ref={container} className="diagram flex min-h-40 items-center justify-center" />
      {error && <p className="text-xs text-red-700">Diagram failed to render: {error}</p>}
    </div>
  );
}
